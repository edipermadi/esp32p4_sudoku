/**
 * @brief how many bits of a 10-bit mask are set (__builtin_popcount())
 * @param[in] m  the mask (bits above 9 are ignored)
 * @return the count
 */
static inline int gen_popcount(unsigned m)
{
    return GEN_BITS_N[m & 0x3FF];
}

/**
 * @brief the lowest bit set in a 10-bit mask (__builtin_ctz()); the smallest digit of a digit mask
 * @param[in] m  the mask, not empty (bits above 9 are ignored)
 * @return the bit
 */
static inline int gen_lowest(unsigned m)
{
    return GEN_BITS_LO[m & 0x3FF];
}

/**
 * @brief the highest bit set in a 10-bit mask (31 - __builtin_clz()); the largest digit of a digit mask
 * @param[in] m  the mask, not empty (bits above 9 are ignored)
 * @return the bit
 */
static inline int gen_highest(unsigned m)
{
    return GEN_BITS_HI[m & 0x3FF];
}

