#!/usr/bin/env python3
"""
Packs the OpenSudoku puzzle collections (tools/opensudoku/*.opensudoku, from
https://opensudoku.gitlab.io/) into src/puzzles_data.c for the firmware.

Each puzzle is 81 digits (0 = empty), packed two cells per byte -> 41 bytes.
Every puzzle is checked to have exactly one solution.

Re-download the source files with:
    cd tools/opensudoku && for f in easy medium hard very_hard \
        gs{1,2,3}_{easy,medium,hard,very_hard}; do \
        curl -fSO https://opensudoku.gitlab.io/opensudoku/$f.opensudoku; done
Then run:  python3 tools/gen_puzzles.py
"""
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(HERE, "opensudoku")
OUT = os.path.join(HERE, "..", "src", "puzzles_data.c")

# (file, display name) in the order shown on the device
COLLECTIONS = [
    ("easy", "Easy"),
    ("medium", "Medium"),
    ("hard", "Hard"),
    ("very_hard", "Very Hard"),
]
for s in (1, 2, 3):
    for f, n in (("easy", "Easy"), ("medium", "Medium"), ("hard", "Hard"), ("very_hard", "Very Hard")):
        COLLECTIONS.append((f"gs{s}_{f}", f"Gnome {s} {n}"))


def count_solutions(grid, limit=2):
    """Bitmask backtracking solver; returns min(#solutions, limit)."""
    g = list(grid)
    rows = [0] * 9
    cols = [0] * 9
    boxes = [0] * 9
    empty = []
    for i, v in enumerate(g):
        r, c = divmod(i, 9)
        b = (r // 3) * 3 + c // 3
        if v:
            m = 1 << v
            if rows[r] & m or cols[c] & m or boxes[b] & m:
                return 0
            rows[r] |= m
            cols[c] |= m
            boxes[b] |= m
        else:
            empty.append(i)
    found = 0

    def rec():
        nonlocal found
        best, best_cands, best_n = -1, 0, 10
        for i in empty:
            if g[i]:
                continue
            r, c = divmod(i, 9)
            b = (r // 3) * 3 + c // 3
            cands = ~(rows[r] | cols[c] | boxes[b]) & 0x3FE
            n = bin(cands).count("1")
            if n < best_n:
                best, best_cands, best_n = i, cands, n
                if n <= 1:
                    break
        if best < 0:
            found += 1
            return found >= limit
        if best_n == 0:
            return False
        r, c = divmod(best, 9)
        b = (r // 3) * 3 + c // 3
        for v in range(1, 10):
            m = 1 << v
            if best_cands & m:
                g[best] = v
                rows[r] |= m
                cols[c] |= m
                boxes[b] |= m
                if rec():
                    return True
                rows[r] &= ~m
                cols[c] &= ~m
                boxes[b] &= ~m
                g[best] = 0
        return False

    rec()
    return found


def main():
    colls = []
    blob = bytearray()
    total = 0
    for fname, name in COLLECTIONS:
        path = os.path.join(SRC_DIR, fname + ".opensudoku")
        root = ET.parse(path).getroot()
        games = [g.get("data") for g in root.iter("game")]
        start = total
        for d in games:
            if len(d) != 81 or not d.isdigit():
                sys.exit(f"{fname}: bad puzzle {d!r}")
            cells = [int(ch) for ch in d]
            n = count_solutions(cells)
            if n != 1:
                sys.exit(f"{fname}: puzzle {d} has {n if n < 2 else '>1'} solutions")
            cells.append(0)  # pad to 82 -> 41 bytes
            for i in range(0, 82, 2):
                blob.append((cells[i] << 4) | cells[i + 1])
            total += 1
        colls.append((name, start, len(games)))
        print(f"{fname:16s} {len(games):4d} puzzles OK")

    with open(OUT, "w") as f:
        f.write("/* Generated by tools/gen_puzzles.py from the OpenSudoku puzzle collections\n"
                " * (https://opensudoku.gitlab.io/). Do not edit. */\n")
        f.write('#include "puzzles.h"\n\n')
        f.write("const puzzle_collection_t puzzle_collections[PUZZLE_COLLECTION_COUNT] = {\n")
        for name, start, n in colls:
            f.write(f'    {{"{name}", {start}, {n}}},\n')
        f.write("};\n\n")
        f.write(f"const uint8_t puzzle_data[PUZZLE_COUNT][PUZZLE_PACKED_BYTES] = {{\n")
        for i in range(total):
            chunk = blob[i * 41:(i + 1) * 41]
            f.write("    {" + ",".join(f"0x{b:02X}" for b in chunk) + "},\n")
        f.write("};\n")

    hdr = os.path.join(HERE, "..", "src", "puzzles_count.h")
    with open(hdr, "w") as f:
        f.write("/* Generated by tools/gen_puzzles.py. Do not edit. */\n#pragma once\n")
        f.write(f"#define PUZZLE_COLLECTION_COUNT {len(colls)}\n#define PUZZLE_COUNT {total}\n")
    print(f"{total} puzzles, {len(blob)} bytes -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
