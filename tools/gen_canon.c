/*
 * The built-in puzzles' canonical hashes (canon_core.h), worked out once and kept in the firmware:
 * writes src/puzzles_canon.c, the table puzzle_canon() reads.
 *
 *     make -C tests canon
 *
 * Run it again whenever the built-in puzzles (src/puzzles_data.c, tools/gen_puzzles.py) or canon_hash()
 * change; the PC tests compare every entry with canon_hash() and fail on a stale table.
 */
#include "canon_core.h"
#include "generator.h"
#include "puzzles.h"
#include <stdio.h>

void sudoku_gen_yield(void) {}

int main(int argc, char **argv)
{
    const char *path = argc > 1 ? argv[1] : "src/puzzles_canon.c";
    FILE *f = fopen(path, "w");
    if (!f) {
        perror(path);
        return 1;
    }
    fprintf(f, "/**\n"
            " * @file puzzles_canon.c\n"
            " * @ingroup canon_core\n"
            " * @brief The built-in puzzles' canonical hashes (canon_core.h), worked out once: generated by\n"
            " *        tools/gen_canon.c (make -C tests canon) from src/puzzles_data.c. Do not edit.\n"
            " */\n"
            "#include \"puzzles.h\"\n\n"
            "/** @brief each built-in puzzle's canon_hash(VAR_CLASSIC, its givens) */\n"
            "static const uint64_t PUZZLE_CANON[PUZZLE_COUNT] = {\n");
    for (int i = 0; i < PUZZLE_COUNT; i++) {
        uint8_t g[81];
        puzzle_load((uint16_t)i, g);
        fprintf(f, "%s0x%016llxULL,%s", i % 3 ? " " : "    ", (unsigned long long)canon_hash(VAR_CLASSIC, g),
                i % 3 == 2 || i == PUZZLE_COUNT - 1 ? "\n" : "");
    }
    fprintf(f, "};\n\n"
            "/* (documented in puzzles.h) */\n"
            "uint64_t puzzle_canon(uint16_t id)\n"
            "{\n"
            "    return id < PUZZLE_COUNT ? PUZZLE_CANON[id] : 0;\n"
            "}\n");
    fclose(f);
    printf("%s: %d hashes\n", path, PUZZLE_COUNT);
    return 0;
}
